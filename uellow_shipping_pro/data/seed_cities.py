City = env['delivery.city'].sudo()
Country = env['res.country'].sudo()
created = updated = 0
for code, items in CITIES.items():
    country = Country.search([('code', '=', code)], limit=1)
    if not country:
        print('!! country missing:', code)
        continue
    existing = {c.name_en.strip().lower(): c
                for c in City.with_context(active_test=False).search(
                    [('country_id', '=', country.id)])}
    for name_en, name_ar in items:
        key = name_en.strip().lower()
        if key in existing:
            rec = existing[key]
            if not rec.name_ar and name_ar:
                rec.name_ar = name_ar
                updated += 1
            if not rec.active:
                rec.active = True
        else:
            City.create({'name_en': name_en, 'name_ar': name_ar,
                         'country_id': country.id})
            created += 1
env.cr.commit()
print('SEED DONE: created=%s updated=%s total=%s' % (
    created, updated, City.search_count([])))
